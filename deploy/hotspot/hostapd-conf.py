#!/usr/bin/python3
"""Write the hostapd config for the guest hotspot from /etc/photobox/config.toml.

Called by photobox-hotspot.service before hostapd starts, so the [hotspot]
section of config.toml is the only place to change name or password.

    hostapd-conf.py /etc/photobox/config.toml /run/photobox-hotspot/hostapd.conf
"""

import os
import sys
import tomllib

INTERFACE = "guestwifi"  # named by /etc/systemd/network/10-photobox-guestwifi.link
CHANNELS = (36, 40, 44, 48)  # 5 GHz only, no radar detection needed


def main(src: str, dest: str) -> None:
    with open(src, "rb") as fh:
        hs = tomllib.load(fh).get("hotspot", {})
    if not hs.get("enabled"):
        sys.exit("hotspot.enabled is not true in " + src)

    ssid = hs.get("ssid", "Photobox")
    password = hs.get("password", "")
    country = hs.get("country", "DE")
    channel = hs.get("channel", 36)
    if not 8 <= len(password) <= 63:
        sys.exit("hotspot.password must be 8 to 63 characters")
    if channel not in CHANNELS:
        sys.exit(f"hotspot.channel must be one of {CHANNELS}")
    for value in (ssid, password, country):
        if "\n" in value or "\r" in value:
            sys.exit("line breaks are not allowed in hotspot settings")

    conf = f"""\
# generated by hostapd-conf.py from {src} - do not edit
interface={INTERFACE}
driver=nl80211
ssid={ssid}
utf8_ssid=1
country_code={country}
ieee80211d=1
# 5 GHz only: shorter range, the network stays near the photobox
hw_mode=a
channel={channel}
ieee80211n=1
ieee80211ac=1
wmm_enabled=1
auth_algs=1
wpa=2
wpa_key_mgmt=WPA-PSK
rsn_pairwise=CCMP
wpa_passphrase={password}
# phones can't see each other, only the photobox
ap_isolate=1
max_num_sta=32
"""
    fd = os.open(dest, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w") as fh:
        fh.write(conf)


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
