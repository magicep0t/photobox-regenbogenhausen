#!/usr/bin/python3
"""Write a hostapd config from /etc/photobox/config.toml.

    hostapd-conf.py guest /etc/photobox/config.toml /run/photobox-hotspot/hostapd.conf
    hostapd-conf.py admin /etc/photobox/config.toml /run/photobox-admin-wifi/hostapd.conf

guest: the 5 GHz hotspot for guests' phones on the USB stick ([hotspot]),
       started by photobox-hotspot.service.
admin: the operator's Wi-Fi on the built-in Wi-Fi in standalone mode
       ([admin_wifi]), started by photobox-admin-wifi.service.

So config.toml is the only place to change names or passwords.
"""

import os
import sys
import tomllib

GUEST_CHANNELS = (36, 40, 44, 48)  # 5 GHz only, no radar detection needed

PROFILES = {
    # section, interface, default SSID, default channel
    "guest": ("hotspot", "guestwifi", "Photobox", 36),
    "admin": ("admin_wifi", "wlan0", "Photobox-Admin", 6),
}


def main(profile: str, src: str, dest: str) -> None:
    section, interface, default_ssid, default_channel = PROFILES[profile]
    with open(src, "rb") as fh:
        cfg = tomllib.load(fh).get(section, {})
    if not cfg.get("enabled"):
        sys.exit(f"{section}.enabled is not true in {src}")

    ssid = cfg.get("ssid", default_ssid)
    password = cfg.get("password", "")
    country = cfg.get("country", "DE")
    channel = cfg.get("channel", default_channel)
    if not 8 <= len(password) <= 63:
        sys.exit(f"{section}.password must be 8 to 63 characters")
    for value in (ssid, password, country):
        if "\n" in value or "\r" in value:
            sys.exit(f"line breaks are not allowed in [{section}]")

    if profile == "guest":
        if channel not in GUEST_CHANNELS:
            sys.exit(f"hotspot.channel must be one of {GUEST_CHANNELS}")
        radio = f"""\
# 5 GHz only: shorter range, the network stays near the photobox
hw_mode=a
channel={channel}
ieee80211n=1
ieee80211ac=1
# phones can't see each other, only the photobox
ap_isolate=1
max_num_sta=32
"""
    else:
        if not 1 <= channel <= 13:
            sys.exit("admin_wifi.channel must be 1 to 13 (2.4 GHz)")
        radio = f"""\
# 2.4 GHz: works with every laptop and reaches the next room
hw_mode=g
channel={channel}
ieee80211n=1
max_num_sta=8
"""

    conf = f"""\
# generated by hostapd-conf.py from {src} - do not edit
interface={interface}
driver=nl80211
ssid={ssid}
utf8_ssid=1
country_code={country}
ieee80211d=1
{radio}wmm_enabled=1
auth_algs=1
wpa=2
wpa_key_mgmt=WPA-PSK
rsn_pairwise=CCMP
wpa_passphrase={password}
"""
    fd = os.open(dest, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w") as fh:
        fh.write(conf)


if __name__ == "__main__":
    if len(sys.argv) != 4 or sys.argv[1] not in PROFILES:
        sys.exit(__doc__)
    main(*sys.argv[1:])
